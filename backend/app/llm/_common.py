"""Общие вспомогательные функции клиентов моделей."""

RUSSIAN_HINT = "Отвечай только на русском языке. Ключи JSON и машинные коды замечаний не переводи."


def with_russian_hint(system: str) -> str:
    """Добавить к системному промпту требование отвечать по-русски."""
    return f"{system.rstrip()}\n\n{RUSSIAN_HINT}"
